# Program Input dan Output Sederhana
# Fungsi input() digunakan untuk meminta data dari pengguna
# Fungsi print() digunakan untuk menampilkan hasil ke layar


nama = input("Masukkan nama kamu: ")  # meminta pengguna memasukkan nama
umur = input("Masukkan umur kamu: ")  # meminta pengguna memasukkan umur


# Menampilkan hasil dengan print
print("Halo,", nama, "!")
print("Umur kamu adalah", umur, "tahun.")
