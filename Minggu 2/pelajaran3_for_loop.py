# Perulangan 'for' digunakan untuk mengulang sejumlah langkah tertentu
# range(5) berarti perulangan dari 0 sampai 4


for i in range(5):  # lakukan 5 kali
    print("Perulangan ke-", i + 1)

    # Contoh lain: mencetak isi list
    buah = ["apel", "mangga", "jeruk"]


for item in buah:
    print("Saya suka", item)
