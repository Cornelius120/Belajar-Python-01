# Tuple mirip dengan list tapi nilainya tidak bisa diubah (immutable)
warna = ("merah", "hijau", "biru")

# Mengakses elemen tuple
print("Warna pertama:", warna[0])

# Tuple berguna untuk data yang tidak boleh diubah
# Misal: koordinat posisi (x, y)
posisi = (10, 20)
print("Koordinat x:", posisi[0])
print("Koordinat y:", posisi[1])
